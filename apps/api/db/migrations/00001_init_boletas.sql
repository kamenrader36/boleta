CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE IF NOT EXISTS boletas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    folio BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE NOT NULL,
    venta_id UUID NOT NULL,
    rut_comprador VARCHAR(12),
    estado VARCHAR(20) NOT NULL DEFAULT 'EMITIDA' CHECK (estado IN ('EMITIDA', 'ANULADA')),
    monto_neto BIGINT NOT NULL CHECK (monto_neto >= 0),
    monto_iva BIGINT NOT NULL CHECK (monto_iva >= 0),
    monto_total BIGINT NOT NULL CHECK (monto_total > 0),
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_anulacion TIMESTAMPTZ,
    motivo_anulacion TEXT,
    referencia_devolucion_stock UUID
);

CREATE TABLE IF NOT EXISTS boleta_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    boleta_id UUID NOT NULL REFERENCES boletas(id) ON DELETE CASCADE,
    producto_id UUID NOT NULL,
    nombre_producto VARCHAR(200) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario BIGINT NOT NULL CHECK (precio_unitario > 0),
    subtotal BIGINT NOT NULL CHECK (subtotal > 0)
);

CREATE TABLE IF NOT EXISTS claves_idempotencia (
    clave UUID PRIMARY KEY,
    operacion VARCHAR(50) NOT NULL,
    estado_http INTEGER NOT NULL,
    respuesta_json JSONB NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

